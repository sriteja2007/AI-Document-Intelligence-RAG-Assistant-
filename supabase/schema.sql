-- ==============================================================================
-- AI Document Intelligence (DocuMind) - Supabase Database Schema
--
-- This script sets up the complete database schema for the RAG assistant.
-- It is idempotent (safe to run more than once without errors).
--
-- Contents:
--   1. Enable Vector Extension (pgvector)
--   2. Table: documents (metadata and processing state for uploaded files)
--   3. Table: chunks (text segments with 768-dimensional AI embeddings)
--   4. Table: conversations (chat sessions for each user)
--   5. Table: messages (user queries and assistant responses with sources)
--   6. Indexes (HNSW cosine similarity index + foreign key performance indexes)
--   7. Row Level Security (RLS policies ensuring users only access their own data)
--   8. Function: match_chunks (semantic vector search with document filtering)
--   9. Trigger: update_conversation_timestamp (auto-updates conversation time on new messages)
-- ==============================================================================


-- ==============================================================================
-- 1. ENABLE THE "VECTOR" EXTENSION
-- Plain English: Enables the pgvector database extension so Postgres can store,
-- index, and perform fast similarity searches on AI mathematical embeddings.
-- ==============================================================================
create extension if not exists vector;


-- ==============================================================================
-- 2. TABLE: DOCUMENTS
-- Plain English: Stores records for every file uploaded by users (PDF, DOCX, TXT),
-- including its storage location, file size, page count, and processing status.
-- ==============================================================================
create table if not exists documents (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    storage_path text not null,
    file_type text not null,
    file_size bigint not null default 0,
    status text not null default 'processing' check (status in ('processing', 'ready', 'failed')),
    error_message text,
    page_count int not null default 0,
    created_at timestamptz not null default now()
);


-- ==============================================================================
-- 3. TABLE: CHUNKS
-- Plain English: Stores broken-down text chunks extracted from documents.
-- Each chunk contains its original text, page number, chunk index order,
-- and the 768-dimension vector embedding generated by the Gemini AI model.
-- ==============================================================================
create table if not exists chunks (
    id uuid primary key default gen_random_uuid(),
    document_id uuid not null references documents(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    content text not null,
    page_number int not null default 1,
    chunk_index int not null default 0,
    embedding vector(768),
    created_at timestamptz not null default now()
);


-- ==============================================================================
-- 4. TABLE: CONVERSATIONS
-- Plain English: Stores chat threads started by users.
-- Tracks the title of the conversation, creation date, and last activity time.
-- ==============================================================================
create table if not exists conversations (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id) on delete cascade,
    title text not null default 'New chat',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);


-- ==============================================================================
-- 5. TABLE: MESSAGES
-- Plain English: Stores individual chat messages exchanged between user and AI.
-- Tracks role ('user' or 'assistant'), message text, and grounded citations (sources).
-- ==============================================================================
create table if not exists messages (
    id uuid primary key default gen_random_uuid(),
    conversation_id uuid not null references conversations(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    sources jsonb not null default '[]'::jsonb,
    created_at timestamptz not null default now()
);


-- ==============================================================================
-- 6. INDEXES
-- Plain English: Creates specialized indexes for blazing-fast database queries:
--   - An HNSW (Hierarchical Navigable Small World) index for instant vector similarity
--   - B-tree indexes on foreign keys to quickly look up items by user, doc, or chat
-- ==============================================================================

-- Fast vector similarity search using cosine distance
create index if not exists chunks_embedding_hnsw_idx
    on chunks using hnsw (embedding vector_cosine_ops);

-- Performance indexes for filtering by user and document
create index if not exists idx_documents_user_id on documents(user_id);
create index if not exists idx_chunks_document_id on chunks(document_id);
create index if not exists idx_chunks_user_id on chunks(user_id);
create index if not exists idx_conversations_user_id on conversations(user_id);
create index if not exists idx_messages_user_id on messages(user_id);
create index if not exists idx_messages_conversation_id on messages(conversation_id);


-- ==============================================================================
-- 7. ROW LEVEL SECURITY (RLS)
-- Plain English: Locks down all four tables so that every user can only view,
-- insert, update, and delete their own rows (user_id = auth.uid()).
-- No user can ever see or modify another user's documents or chats.
-- ==============================================================================

-- Enable Row Level Security on all tables
alter table documents enable row level security;
alter table chunks enable row level security;
alter table conversations enable row level security;
alter table messages enable row level security;

-- ------------------------------------------------------------------------------
-- 7a. RLS Policies for: documents
-- ------------------------------------------------------------------------------
