-- ==============================================================================
-- 8. FUNCTION: MATCH_CHUNKS
-- Plain English: Finds the most relevant document chunks for a user's question.
-- Compares the AI vector of the question against stored document chunks.
-- Filters only chunks belonging to the specified user and to 'ready' documents,
-- optionally narrows the search down to specific documents (p_document_ids),
-- and orders from closest match to furthest match up to match_count.
-- ==============================================================================
create or replace function match_chunks(
    query_embedding vector(768),
    match_count int,
    p_user_id uuid,
    p_document_ids uuid[] default null
)
returns table (
    id uuid,
    document_id uuid,
    document_name text,
    content text,
    page_number int,
    similarity float8
)
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
    return query
    select
        c.id,
        c.document_id,
        d.name as document_name,
        c.content,
        c.page_number,
        (1 - (c.embedding <=> query_embedding)) as similarity
    from chunks c
    inner join documents d on c.document_id = d.id
    where c.user_id = p_user_id
      and d.status = 'ready'
      and (
          p_document_ids is null
          or cardinality(p_document_ids) = 0
          or c.document_id = any(p_document_ids)
      )
    order by c.embedding <=> query_embedding
    limit match_count;
end;
$$;

-- Grant execution permissions on match_chunks to authenticated users and backend
grant execute on function match_chunks(vector(768), int, uuid, uuid[]) to authenticated, service_role;


-- ==============================================================================
-- 9. TRIGGER: UPDATE CONVERSATION TIMESTAMP
-- Plain English: Automatically refreshes the conversation's 'updated_at' timestamp
-- whenever a new message is inserted, keeping the chat list sorted by recency.
-- ==============================================================================

-- Function invoked by the trigger
create or replace function update_conversation_timestamp()
returns trigger
language plpgsql
as $$
begin
    update conversations
    set updated_at = now()
    where id = new.conversation_id;
    return new;
end;
$$;

-- Trigger attached to messages table
drop trigger if exists trigger_update_conversation_timestamp on messages;
create trigger trigger_update_conversation_timestamp
    after insert on messages
    for each row
    execute function update_conversation_timestamp();
